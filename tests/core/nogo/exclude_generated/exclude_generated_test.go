package exclude_generated_test

import (
	"os"
	"strings"
	"testing"

	"github.com/bazelbuild/rules_go/go/tools/bazel_testing"
)

func TestMain(m *testing.M) {
	bazel_testing.TestMain(m, bazel_testing.Args{
		Nogo: "@//:nogo",
		Main: `
-- BUILD.bazel --
load("@io_bazel_rules_go//go:def.bzl", "go_library", "nogo")

nogo(
    name = "nogo",
    config = "config.json",
    deps = [":foofuncname"],
    visibility = ["//visibility:public"],
)

go_library(
    name = "foofuncname",
    srcs = ["foofuncname.go"],
    importpath = "foofuncname",
    deps = ["@org_golang_x_tools//go/analysis"],
)

go_library(
    name = "generated",
    srcs = ["generated.go"],
    importpath = "generated",
)

go_library(
    name = "handwritten",
    srcs = ["handwritten.go"],
    importpath = "handwritten",
)

-- config.json --
{
  "_base": {
    "exclude_generated": true
  }
}

-- foofuncname.go --
package foofuncname

import (
	"go/ast"

	"golang.org/x/tools/go/analysis"
)

var Analyzer = &analysis.Analyzer{
	Name: "foofuncname",
	Doc:  "reports functions named Foo",
	Run: func(pass *analysis.Pass) (interface{}, error) {
		for _, f := range pass.Files {
			for _, d := range f.Decls {
				if fn, ok := d.(*ast.FuncDecl); ok && fn.Name.Name == "Foo" {
					pass.Reportf(fn.Pos(), "function must not be named Foo")
				}
			}
		}
		return nil, nil
	},
}

-- generated.go --
// Code generated by hand for this test. DO NOT EDIT.

package generated

func Foo() {}

-- handwritten.go --
package handwritten

func Foo() {}
`,
	})
}

// With exclude_generated, the generated file passes and the hand-written one
// still fails.
func TestExcludeGenerated(t *testing.T) {
	if err := bazel_testing.RunBazel("build", "//:generated"); err != nil {
		t.Fatalf("expected nogo to skip the generated file, got:\n%s", err)
	}
	expectFoofuncname(t, "//:handwritten")
}

// Without exclude_generated, the generated file is checked like any other.
func TestWithoutExcludeGenerated(t *testing.T) {
	if err := os.WriteFile("config.json", []byte("{}"), 0o666); err != nil {
		t.Fatal(err)
	}
	expectFoofuncname(t, "//:generated")
}

func expectFoofuncname(t *testing.T, target string) {
	t.Helper()
	err := bazel_testing.RunBazel("build", target)
	if err == nil {
		t.Fatalf("expected building %s to fail on a foofuncname finding", target)
	}
	if want := "function must not be named Foo (foofuncname)"; !strings.Contains(err.Error(), want) {
		t.Fatalf("expected the build error for %s to contain %q, got:\n%s", target, want, err)
	}
}
